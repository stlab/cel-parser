"""Generates sorted Unicode 18 XID ranges from the versioned UCD source."""
import hashlib
from pathlib import Path
import urllib.request

URL = "https://www.unicode.org/Public/18.0.0/ucd/DerivedCoreProperties.txt"
SHA256 = "09c928886a178fcafd93c29e4bd59073a058e5a100b716d425cb563ab50f68c9"


def generate():
    """Writes deterministic private XID tables and records the input digest."""
    data = urllib.request.urlopen(URL).read()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError("Unicode 18 source digest differs from the reviewed input")
    properties = {"XID_Start": [], "XID_Continue": []}
    for line in data.decode("utf-8").splitlines():
        entry = line.partition("#")[0].strip()
        if not entry:
            continue
        bounds, _, prop = entry.partition(";")
        prop = prop.strip()
        if prop not in properties:
            continue
        lo, _, hi = bounds.strip().partition("..")
        interval = (int(lo, 16), int(hi or lo, 16))
        ranges = properties[prop]
        if ranges and ranges[-1][1] + 1 == interval[0]:
            ranges[-1] = (ranges[-1][0], interval[1])
        else:
            ranges.append(interval)
    output = [
        "// SPDX-License-Identifier: Unicode-3.0",
        "// Generated by tools/generate_unicode.py; Unicode 18.0.0.",
        f"// Input: {URL}",
        f"// SHA-256: {hashlib.sha256(data).hexdigest()}",
        "#ifndef CEL_PARSER_UNICODE_DATA_HPP",
        "#define CEL_PARSER_UNICODE_DATA_HPP",
        "#include <array>",
        "#include <cstdint>",
        "namespace cel::detail {",
        "/// Stores an inclusive Unicode property interval.",
        "struct unicode_range { std::uint32_t first; std::uint32_t last; };",
    ]
    for prop, ranges in properties.items():
        output += [f"/// Stores Unicode 18 {prop} intervals in ascending order.",
                   f"inline constexpr std::array<unicode_range, {len(ranges)}> {prop.lower()}{{{{"]
        output += [f"    {{0x{lo:X}, 0x{hi:X}}}," for lo, hi in ranges]
        output += ["}};"]
    output += ["} // namespace cel::detail", "#endif", ""]
    Path("src/unicode_data.hpp").write_text("\n".join(output))
    print(f"Unicode 18 input SHA-256: {hashlib.sha256(data).hexdigest()}")
    print({prop: len(ranges) for prop, ranges in properties.items()})


if __name__ == "__main__":
    generate()
